## @class PVALUE
#  Helper base class to run permutation/bootstrap test in parallel
class PVALUE (abc.ABC) :
    """ Helper base class that allows running permutation/bootstrap tests 
    """
    def __init__ ( self        ,
                   gof         ,
                   t_value     ,
                   ds1         ,
                   ds2         ,
                   weight1     = None ,
                   weight2     = None ,
                   random_seed = None ,
                   description = 'Permutations:') :
        
        self.gof     = gof
        self.t_value = t_value
        self.ecdf    = None

        w1_trivial   = weight_trivial ( weight1 )
        w2_trivial   = weight_trivial ( weight2 )

        if w1_trivial and w2_trivial :
            weight1 , weight2 = None, None 

        w1mean = -1000 if w1_trivial else numpy.mean ( weight1 ) 
        w2mean = -1000 if w2_trivial else numpy.mean ( weight2 ) 
        
        self.ds1         = ds1
        self.ds2         = ds2
        self.weight1     = weight1
        self.weight2     = weight2
        self.random_seed = random_seed 
        self.description = description
        
    # =========================================================================
    ## Serialize the object for multiprocessing
    def __getstate__ ( self ) :
        """ Serialize state dictionary without redundant original ds2
        """
        return { 'gof'         : self.gof     ,
                 't_value'     : self.t_value , 
                 'ecdf'        : self.ecdf    ,
                 'ds1'         : self.ds1     ,   
                 'ds2'         : self.ds2     ,   
                 'weight1'     : self.weight1 ,
                 'weight2'     : self.weight2 ,
                 'random_seed' : self.random_seed , 
                 'description' : self.description }
    
    ## De-serialize the object
    def __setstate__ ( self , state ) :
        """ Restore object state from dictionary
        """
        self.gof         = state.pop ( 'gof'         )
        self.t_value     = state.pop ( 't_value'     )
        self.ecdf        = state.pop ( 'ecdf'        )
        self.ds1         = state.pop ( 'ds1'         )
        self.ds2         = state.pop ( 'ds2'         )
        self.weight1     = state.pop ( 'weight1'     )
        self.weight2     = state.pop ( 'weight2'     )
        self.random_seed = state.pop ( 'random_seed' )
        self.description = state.pop ( 'description' )
        
    # =========================================================================
    ## Run N-permutations/boostrapping  on callable execution
    def __call__ ( self , N , silent = True , progress = False ) :
        """ Run N-permutations/boostrapping  on callable execution
        """        
        counter, tvalues = self.run_toys ( N        =  N       ,
                                           silent   = silent   ,
                                           progress = progress )
        
        if not self.ecdf : self.ecdf = ECDF ( tvalues , True )
        else             : self.ecdf.add ( data2vct ( tvalues )  )
        
        return counter, numpy.asarray ( tvalues , dtype = float ) 

    # =========================================================================
    ## Run NN-permutations in parallel using the default ostap' WorkManager
    def run ( self , N , silent = False , progress  = True ) :
        """ Execute permutations/bootstrap in parallel using ostap' WorkManager
        """
        ##
        from ostap.utils.basic  import numcpu
        from ostap.utils.memory import memory_enough
        from ostap.utils.utils  import splitter
        ## 
        me       = math.floor ( memory_enough() ) + 1 
        njobs    = 5 * numcpu () + 1 
        the_list = [ n for n in splitter ( N , njobs ) ] 
        njobs    = len ( the_list ) 

        if not silent : logger.info ( 'GoF p-value: #%d parallel subjobs to be used with WorkManager' %  njobs )
        
        counter = EffCounter()
        tvalues = () 
        
        from ostap.parallel.parallel import WorkManager
        with WorkManager ( silent = silent ) as manager : 
            for result in manager.iexecute ( self.run_toys ,
                                             the_list      ,
                                             block_size    = min ( me , 2 * numcpu() ) , 
                                             progress      = progress         ,
                                             njobs         = njobs            ,
                                             description   = self.description ) :
                cnt , tvals = result 
                counter += cnt
                tvalues += tuple ( float ( t ) for t in tvals )
        
        if not self.ecdf : self.ecdf = ECDF ( tvalues , True )
        else             : self.ecdf.add    ( data2vct ( tvalues )      )
        
        return counter, numpy.asarray ( tvalues , dtype = float ) 
    
    # ========================================================================
    ## Run N-toys/permutatino/bootstrappings/...
    @abc.abstractmethod 
    def run_toys ( self, N , silent = True , progress = False ) :
        """ Run N-toys/permutations/bootstrappings/...
        """
        return NotImplemented

