## @class BOOTSTRAPPER
#  Helper class to run bootstrap tests in parallel
class BOOTSTRAPPER (PERMUTATOR) :
    """ Helper class that allows running bootstrap tests in parallel,
    """
    def __init__ ( self        ,
                   gof         ,
                   t_value     ,
                   ds1         ,
                   ds2         ,
                   weight1     = None ,
                   weight2     = None ,
                   random_seed = None ,                    
                   description = 'Bootstrapping:' ) :

        super().__init__ ( gof         = gof         ,
                           t_value     = t_value     ,
                           ds1         = ds1         ,
                           ds2         = ds2         ,
                           weight1     = weight1     ,
                           weight2     = weight2     ,
                           random_seed = random_seed ,                            
                           description = description )

    # =========================================================================
    ## Run N-toys over prepared bootstrap samples
    def run_toys ( self , N , silent = True , progress = False ) :
        """ Run N bootstrap pseudo-experiments (toys) across pre-calculated slices
        """        
        counter = EffCounter()
        tvalues = []
        
        for data1 , data2 , weight1 , weight2 in make_bootstrap ( N           ,
                                                                  self.ds1    ,
                                                                  self.ds2    ,
                                                                  weight1     = self.weight1     ,
                                                                  weight2     = self.weight2     ,
                                                                  progress    = progress         ,   
                                                                  silent      = silent           ,
                                                                  random_seed = self.random_seed ) :
                        
            ## Note: normalize = False is required for sliced evaluation
            tv = self.gof.tvalue ( data1     ,
                                   data2     ,
                                   weight1   = weight1 ,
                                   weight2   = weight2 ,
                                   normalize = False   )
            tvalues.append ( float ( tv ) )

        for tv in tvalues : counter += bool ( self.t_value <= tv  )
        
        return counter , numpy.asarray ( tvalues , dtype = float )
    
