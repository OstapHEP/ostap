## Helper generator to produce N permutations resamples from pooled datasets under H0
#  1. Pooled dataset is created
#  2. Indices are chosen with replacement for pooled bootstrap
#  3. If present, weights are renormalized to preserve original sample masses
def make_permutations ( N           ,
                        data1       ,
                        data2       , *     ,
                        weight1     = None  ,
                        weight2     = None  ,
                        silent      = True  ,
                        progress    = True  ,
                        random_seed = None  , 
                        description = "Permutations:" ) :
    """ Yields (data1, data2, weight1, weight2) pairs generated by pooled
    resampling with replacement under H0. Preserves the exact initial weight
    sum normalization for both samples.
    """
    return make_resampling ( sampler     = _permutations , 
                             N           = N             ,
                             data1       = data1         ,
                             data2       = data2         ,
                             weight1     = weight1       ,
                             weight2     = weight2       ,
                             silent      = silent        ,
                             progress    = progress      ,
                             random_seed = random_seed   ,
                             description = description   ) 

# =============================================================================
## Helper generator to produce N bootstrap resamples from pooled datasets under H0
#  1. Pooled dataset is created
#  2. Indices are chosen with replacement for pooled bootstrap
#  3. If present, weights are renormalized to preserve original sample masses
def make_bootstrap ( N           ,
                     data1       ,
                     data2       , *     ,
                     weight1     = None  ,
                     weight2     = None  ,
                     silent      = True  ,
                     random_seed = None  , 
                     progress    = True  ,
                     description = "Boostrapping:" ) :
    """ Yields (data1, data2, weight1, weight2) pairs generated by pooled
    resampling with replacement under H0. Preserves the exact initial weight
    sum normalization for both samples.
    """
    return make_resampling ( sampler     = _bootstrap  , 
                             N           = N           ,
                             data1       = data1       ,
                             data2       = data2       ,
                             weight1     = weight1     ,
                             weight2     = weight2     ,
                             silent      = silent      ,
                             progress    = progress    , 
                             random_seed = random_seed ,
                             description = description ) 

    
