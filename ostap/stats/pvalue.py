## Sampling without replacement (Permutations)
def _permutations ( rng , n1 , n2  ) :
    """ Sampling without replacement (Permutations)
    """
    return numpy.split ( rng.permutation ( n1 + n2 ) , [ n1 ] )
# ============================================================================
## Sampling with replacement (Bootstrap)
def _bootstrap   ( rng , n1 , n2 ) :
    """ Sampling with replacement (Bootstrap)
    """
    idx1 = rng.integers ( 0, n1 + n2 , size = n1 )
    idx2 = rng.integers ( 0, n1 + n2 , size = n2 )
    return idx1 , idx2
