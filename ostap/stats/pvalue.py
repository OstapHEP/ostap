## @class TOYS
#  Helper class to run toys for Goodness-of-Fit studies 
class TOYS (PVALUE) :
    """ Helper class that allow to run toys in parallel 
    """
    def __init__ ( self    , 
                   gof     , *         , 
                   t_value             ,
                   pdf                 ,
                   Ndata               , 
                   sample      = False ,
                   parameters  = {}    ,
                   random_seed = None  ) :
        
        from ostap.fitting.pdfbasic import APDF1
        if not isinstance ( pdf , APDF1 ) : raise TypeError ( "%s: invaild `pdf` type:%s" % ( typename ( self ) , typename ( pdf ) ) )
        
        
        self.pdf        = pdf
        self.Ndata      = Ndata 
        self.sample     = gof.sample 

        if parameters : self.parameters = parameters
        else          : self.parameters = pdf.dct_params () 

        super().__init__ ( gof         = gof         , 
                           t_value     = t_value     ,
                           ds1         = None        ,
                           ds2         = None        ,
                           random_seed = random_seed ,                                                       
                           description = 'Toys:'     )
        
    # =========================================================================
    ## serialize the object 
    def __getstate__ ( self ) :
        """ Serialize the object
        """
        ## the base 
        state  = super().__getstate__ () 
        
        self.pdf.load_params ( self.parameters , silent = True )
        state [ 'pdf'        ] = self.pdf
        state [ 'Ndata'      ] = self.Ndata
        state [ 'sample'     ] = self.sample 
        state [ 'parameters' ] = self.parameters 
        return state

    # =========================================================================
    ## de-serialize the object 
    def __setstate__ ( self , state ) :
        """ De-serialize the object
        """
        super().__setstate__ ( self , state )
        
        self.pdf         = state.pop ( 'pdf'        )
        self.Ndata       = state.pop ( 'Ndata'      )
        self.sample      = state.pop ( 'sample'     )
        self.parameters  = state.pop ( 'parameters' )

        ## (1) re-load parameters 
        self.pdf.load_params ( self.parameters , silent = True )

    # =========================================================================
    ## run N-toys 
    def run_toys ( self , N , silent = True , progress = False ) :
        """ Run N-toys
        """
        
        seed = self.random_seed
        if not seed : seed = 0
        
        import ROOT 
        ROOT.gRandom                     .SetSeed ( seed ) 
        ROOT.RooRandom.randomGenerator() .SetSeed ( seed )

        counter = EffCounter ()
        tvalues = [] 
        for i in progress_bar ( N , description = self.description , silent = not progress ) : 

            ## for consistency
            self.pdf.load_params ( self.parameters , silent = True )
            
            dset     = self.pdf.generate ( self.Ndata , sample = self.sample )
            tv       = self.gof ( self.pdf , dset )
            counter += bool ( self.t_value > tv   ) ## NOTE THE SIGN HERE!

            tvalues.append ( tv ) 

            if isinstance  ( dset , ROOT.RooDataSet ) :
                dset.clear ()
                ROOT.SetOwnership ( dset , True )
                del dset

        if not self.ecdf : self.ecdf = ECDF ( tvalues  , True ) 
        else             : self.ecdf.add ( data2vct ( tvalues )  )

        return counter, numpy.asarray ( tvalues , dtype = float ) 

