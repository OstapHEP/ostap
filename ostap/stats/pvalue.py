## @class PERMUTATOR
#  Helper class to run permutation test in parallel with optional dataset slicing.
class PERMUTATOR (PVALUE) :
    """ Helper class that allows running permutation tests in parallel,
    with support for slicing large datasets (ds2) into sub-samples.
    """
    # =========================================================================
    def __init__ ( self        ,
                   gof         ,
                   t_value     ,
                   ds1         ,
                   ds2         ,
                   weight1     = None ,
                   weight2     = None ,
                   random_seed = None , 
                   description = 'Permutations:' ) :
        
        check_all ( ds1 , ds2, weight1 , weight2 , typename  ( self ) )
        
        super().__init__ ( gof         = gof         ,
                           t_value     = t_value     ,
                           ds1         = ds1         ,
                           ds2         = ds2         ,
                           weight1     = weight1     ,
                           weight2     = weight2     ,
                           random_seed = random_seed , 
                           description = description )
        
    ## Run N permutations 
    def run_toys ( self, N , silent = True , progress = False ) :
        """ Run N permutations 
        """        
        counter = EffCounter()
        tvalues = []

        for data1 , data2 , weight1 , weight2 in make_permutations ( N ,
                                                                     self.ds1                   ,
                                                                     self.ds2                   ,
                                                                     weight1     = self.weight1 ,
                                                                     weight2     = self.weight2 ,
                                                                     progress    = progress     ,   
                                                                     silent      = silent       ,
                                                                     random_seed = self.random_seed ) :
            
            ## Note: normalize = False is required for sliced evaluation
            tv       = self.gof.tvalue ( data1     ,
                                         data2     ,
                                         weight1   = weight1 ,
                                         weight2   = weight2 ,
                                         normalize = False   )
            tv       = float ( tv )
            tvalues.append   ( tv  )
            counter += bool  ( self.t_value <= tv  )
            
        return counter , numpy.asarray ( tvalues , dtype = float )

