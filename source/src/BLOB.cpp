{
#if defined(OSTAP_HAS_STD_BYTE) && OSTAP_HAS_STD_BYTE
  static_assert ( sizeof ( std::byte ) == sizeof ( Char_t ) ,"Mismatch in std::byte/Char_t size!" ) ;
  static_assert ( sizeof ( std::byte ) == sizeof ( char   ) ,"Mismatch in std::byte/char size!" ) ;
#endif // OSTAP_HAS_STD_BYTE
}
// ========================================================================
// Standard constructor
// ============================================================================
Ostap::BLOB::BLOB
( const std::string& name   , 
  const std::string& title  ,
  const std::size_t  len    , 
  const void*        buffer ) 
  : TNamed ( name , title ) 
  , m_data () 
{
  if  ( len && buffer ) 
  {
    char* data = new char [ len ] ;
    std::memcpy ( data , buffer , len ) ;
    m_data.Adopt ( len , data ) ;  
  }
}
// ============================================================================
// destructor 
// ============================================================================
Ostap::BLOB::~BLOB(){}
// ============================================================================
// redefine the buffer 
// ============================================================================
void Ostap::BLOB::setBuffer
( const std::size_t size   , 
  const void*       buffer ) 
{ m_data.Set ( size , (const char*) buffer ) ; }
